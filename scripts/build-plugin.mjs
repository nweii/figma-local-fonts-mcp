// Packages canonical skills, a self-contained local MCP, and credential-free Figma setup resources for agent clients.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const destination = 'plugins/agent-font-access';
const manifest = JSON.parse(await readFile('plugin-package/plugin.json', 'utf8'));
const json = value => JSON.stringify(value, null, 2) + '\n';
for (const directory of ['server', 'scripts', 'figma', 'docs', 'skills', '.claude-plugin']) await mkdir(join(destination, directory), { recursive: true });
await writeFile(join(destination, 'plugin.json'), json(manifest));
const { $schema, extensions, ...claude } = manifest;
await writeFile(join(destination, '.claude-plugin/plugin.json'), json(claude));
const server = { type: 'stdio', command: 'node', args: ['${PLUGIN_ROOT}/server/server.mjs'] };
await writeFile(join(destination, 'mcp.json'), json({ $schema: 'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json', mcpServers: { figma_local_fonts: server } }));
await writeFile(join(destination, '.mcp.json'), json({ mcpServers: { figma_local_fonts: { ...server, args: ['${CLAUDE_PLUGIN_ROOT}/server/server.mjs'] } } }));
const common = { bundle: true, platform: 'node', format: 'esm', target: 'node24', external: ['bufferutil', 'utf-8-validate'],
  banner: { js: '// Bundled Agent Font Access runtime; generated by scripts/build-plugin.mjs.\nimport { createRequire as pluginCreateRequire } from "node:module"; const require = pluginCreateRequire(import.meta.url);' }, metafile: true };
const outputs = [];
for (const [entry, output] of [['src/server.ts', 'server/server.mjs'], ['src/broker.ts', 'server/broker.js'], ['scripts/prepare-companion.mjs', 'scripts/prepare-companion.mjs']]) {
  outputs.push(await build({ ...common, entryPoints: [entry], outfile: join(destination, output) }));
}
// The broker filename is fixed by the MCP entry point; declare ESM for its .js extension.
await writeFile(join(destination, 'package.json'), json({ name: 'agent-font-access', version: manifest.version, private: true, type: 'module', engines: { node: '>=24' } }));
await build({ entryPoints: ['src/plugin.ts'], outfile: join(destination, 'figma/code.js'), bundle: true, platform: 'browser', format: 'iife', target: 'es2017', banner: { js: '// Figma Desktop text companion, generated from src/plugin.ts.' } });
await cp('plugin/manifest.json', join(destination, 'figma/manifest.json'));
await cp('src/ui.html', join(destination, 'figma/ui.template.html'));
await cp('skills', join(destination, 'skills'), { recursive: true });
await cp('docs', join(destination, 'docs'), { recursive: true });
await cp('LICENSE', join(destination, 'LICENSE'));
await cp('PRIVACY.md', join(destination, 'PRIVACY.md'));
await cp('SECURITY.md', join(destination, 'SECURITY.md'));
await cp('CHANGELOG.md', join(destination, 'CHANGELOG.md'));
await cp('README.md', join(destination, 'README.md'));
const packages = new Set(outputs.flatMap(output => Object.keys(output.metafile.inputs)).filter(path => path.startsWith('node_modules/')).map(path => {
  const parts = path.split('/'); return parts[1].startsWith('@') ? parts.slice(0, 3).join('/') : parts.slice(0, 2).join('/');
}));
let notices = '# Bundled dependency licenses\n';
for (const directory of [...packages].sort()) {
  const pkg = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  for (const name of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENSE-MIT']) {
    try { notices += `\n## ${pkg.name} ${pkg.version}\n\n${await readFile(join(directory, name), 'utf8')}\n`; break; }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
}
await writeFile(join(destination, 'THIRD_PARTY_NOTICES.txt'), notices);
const claudeDestination = 'plugins/agent-font-access-claude';
await cp(destination, claudeDestination, { recursive: true });
await rm(join(claudeDestination, 'plugin.json'));
await rm(join(claudeDestination, 'mcp.json'));
await rm(join(destination, '.claude-plugin'), { recursive: true });
await rm(join(destination, '.mcp.json'));
console.log(`Built ${destination} and ${claudeDestination} with skill, local MCP, and unpaired Figma resources.`);
